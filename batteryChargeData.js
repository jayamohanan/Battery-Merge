// Helper function to get charge value for a battery level
// Falls back to level * 5 if level not in table
function getBatteryChargeValue(level) {
    if (BATTERY_CHARGE_TABLE.hasOwnProperty(level)) {
        return BATTERY_CHARGE_TABLE[level];
    }
    // Fallback for levels not defined in table
    return level * 5;
}
